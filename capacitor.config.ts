import type { CapacitorConfig } from "@capacitor/cli";

/**
 * Fridge Ops — Android shell (Capacitor).
 *
 * Architecture A: the app is a native window around OUR deployed server. It opens
 *   <CAP_SERVER_URL>   (default path /m — the employee interface)
 * All data, auth, KitShop access and the database stay on the server.
 * This file contains NO secrets — only the public server address.
 *
 *   CAP_SERVER_URL=https://ops.example.kz/m npm run cap:sync      ← production
 *   CAP_SERVER_URL=http://192.168.1.50:3000/m npm run cap:sync    ← development on local Wi-Fi
 */
const serverUrl = process.env.CAP_SERVER_URL || "https://fridge-ops.onrender.com/m";
const isHttp = serverUrl.startsWith("http://");

const config: CapacitorConfig = {
  appId: "kz.greencity.fridgeops",
  appName: "Fridge Ops",
  // local fallback pages (index + offline) generated by scripts/cap-prepare.mjs
  webDir: "capacitor-www",
  server: {
    url: serverUrl,
    // cleartext only for local development over http://
    cleartext: isHttp,
    androidScheme: "https",
    // shown when the server cannot be reached (no internet / server down)
    errorPath: "offline.html",
  },
  android: {
    allowMixedContent: false,
    backgroundColor: "#0b0c0e",
    webContentsDebuggingEnabled: process.env.CAP_DEBUG === "true",
  },
  plugins: {
    SplashScreen: {
      launchShowDuration: 800,
      backgroundColor: "#0b0c0e",
      showSpinner: false,
    },
  },
};

export default config;
