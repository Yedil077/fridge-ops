/**
 * KiT Shop write operations, as Fridge Ops records them (our database is the journal; KiT Shop is the target).
 * See docs/KITSHOP_WRITE_API_AUDIT.md for what the KiT Shop API can and cannot do.
 */

export type OpType = "LOAD" | "UNLOAD" | "WRITE_OFF";

export type OpStatus =
  /** created, not sent yet */
  | "DRAFT"
  /** being sent / waiting for KiT Shop's answer */
  | "PENDING"
  /** KiT Shop answered OK (or the verification found it) */
  | "CONFIRMED"
  /** KiT Shop rejected it — nothing was applied; may be re-sent manually */
  | "FAILED"
  /** sent, but no answer (timeout / lost) — NEVER re-sent automatically; verified via read methods */
  | "UNKNOWN"
  /** automatic verification impossible — a manager must check the KiT Shop cabinet */
  | "REQUIRES_REVIEW"
  /** KiT Shop provably not reached — will be sent (once) when the connection is back */
  | "WAITING_FOR_CONNECTION";

export type AdapterMode = "mock" | "dry-run" | "live";

export type OpOrigin = "app" | "write-test";

export type OpErrorCode =
  | "WRITES_PAUSED"
  | "MAPPING_REQUIRED"
  | "NOT_IN_SHOP_BASE"
  | "NO_RIGHTS"
  | "SHOP_NOT_FOUND"
  | "KITSHOP_ERROR"
  | "SOURCE_NOT_CONFIRMED";

export interface OpLine {
  /** our product id */
  productId: string;
  /** stable KiT Shop ProductId (never inferred from the name) */
  kitshopProductId: string;
  name: string;
  /** always positive; the sign for KiT Shop follows from the operation type */
  qty: number;
}

export interface OpHistoryEntry {
  at: number;
  status: OpStatus;
  note: string;
}

export interface KsOperation {
  /** operation_uuid, generated by the client: the idempotency key */
  id: string;
  type: OpType;
  fridgeId: string;
  /** stable KiT Shop ShopId */
  shopId: string;
  fridgeName: string;
  lines: OpLine[];
  /** WRITE_OFF reason (expired, damaged, …) */
  reason: string | null;
  status: OpStatus;
  errorCode: OpErrorCode | null;
  error: string | null;
  createdAt: number;
  createdBy: string;
  /** last time it was handed to KiT Shop */
  sentAt: number | null;
  /** how many times the request really left our server (should be 1) */
  attempts: number;
  confirmedAt: number | null;
  kitshopFillupId: string | null;
  adapterMode: AdapterMode;
  /** mission / transfer link: TRANSFER = source UNLOAD + target LOAD */
  missionId: string | null;
  transferId: string | null;
  transferRole: "source" | "target" | null;
  /** the target LOAD waits until the source UNLOAD is confirmed */
  dependsOn: string | null;
  /** apply the confirmed change to the simulator (standalone ops in MOCK mode; missions move stock themselves) */
  applyToSim: boolean;
  /** "write-test" = the admin REAL WRITE TEST wizard (the only origin allowed to write live while KITSHOP_WRITE_SCOPE=test) */
  origin?: OpOrigin;
  history: OpHistoryEntry[];
}

export interface AuditEntry {
  id: string;
  at: number;
  user: string;
  action: string;
  entity: string;
  entityId: string;
  details: Record<string, unknown>;
}

/** What KiT Shop's MakeFillUp receives (Fillup > 0 load, < 0 unload). */
export interface FillUpRequest {
  operationId: string;
  shopId: string;
  notes: string;
  lines: { kitshopProductId: string; fillup: number }[];
}

export type WriteOutcome =
  | { kind: "ok"; message?: string; fillupId?: string }
  /** KiT Shop answered and refused — nothing applied */
  | { kind: "rejected"; code: number; message: string }
  /** sent, no reliable answer */
  | { kind: "unknown"; reason: string }
  /** provably not sent */
  | { kind: "unreachable"; reason: string };

export type VerifyOutcome =
  | { kind: "found"; fillupId: string | null }
  | { kind: "absent" }
  /** cannot tell (verification not supported / read failed) */
  | { kind: "unverifiable"; reason: string };

export interface CatalogProductInput {
  name: string;
  barcode: string | null;
  vendorCode: string | null;
  price: number | null;
  /** Appendix 6/3/7 codes — confirmed with the business before use */
  unitType: number;
  taxType: number;
  accuracyType: number;
}

export interface KitShopWriteAdapter {
  readonly mode: AdapterMode;
  makeFillUp(req: FillUpRequest): Promise<WriteOutcome>;
  /** looks for our operation in KiT Shop (by the FO:<uuid> marker in Notes) */
  verifyFillUp(op: { id: string; shopId: string; sentAt: number }): Promise<VerifyOutcome>;
  addProduct(p: CatalogProductInput): Promise<WriteOutcome & { productId?: string }>;
}

