import fs from "node:fs";
import path from "node:path";
import type { Mission, Weekday } from "../domain/types";
import type { LearningState } from "../engine/feedback";
import type { SimState } from "../simulator/simulator";

/**
 * Our own data (never KitShop's): users & sessions, missions/routes, XP / points, rewards,
 * learning tables, fridge settings, notifications, simulator state.
 *
 * ONE source of truth for every client (desktop web, mobile PWA, Android app):
 *  • STORE_DRIVER=postgres — production: the state lives in PostgreSQL (see store/pgStore.ts)
 *  • STORE_DRIVER=file     — local development: .data/app-state.json (git-ignored)
 * Phones keep only temporary offline progress; they are never the source of truth.
 */

export type Role = "EMPLOYEE" | "MANAGER" | "ADMIN";

export interface User {
  id: string;
  /** lowercase login, unique */
  login: string;
  /** display name — also the key of the player profile */
  name: string;
  role: Role;
  /** scrypt hash of the PIN — never the PIN itself */
  pinHash: string;
  active: boolean;
  createdAt: number;
  pinUpdatedAt: number;
}

export interface Session {
  id: string;
  userId: string;
  /** sha256 of the random token stored in the httpOnly cookie */
  tokenHash: string;
  device: string;
  createdAt: number;
  lastSeenAt: number;
  expiresAt: number;
  revokedAt: number | null;
  revokedBy: string | null;
}

export interface XpEvent {
  at: number;
  user: string;
  amount: number;
  points: number;
  reason: string;
  missionId: string | null;
}

export interface Player {
  name: string;
  xp: number;
  /** OPS POINTS — earned only for confirmed results; drive reward milestones. */
  points: number;
  /** consecutive evaluated missions with a good result (≥ 50% sold) */
  streak: number;
  bestStreak: number;
  achievements: Record<string, number>; // id → unlocked at
  counters: { hotStockoutsPrevented: number; wasteSaved: number; perfectRoutesInRow: number; fastUrgent: number };
}

export interface RewardClaim {
  id: string;
  user: string;
  milestoneId: string;
  title: string;
  points: number;
  unlockedAt: number;
  issuedAt: number | null;
  issuedBy: string | null;
}

/** Admin-editable overrides on top of the data source (names, schedule, routing). */
export interface FridgeSettings {
  displayName?: string;
  shortName?: string;
  location?: string;
  priority?: 1 | 2 | 3;
  proximityGroup?: string | null;
  transferGroup?: string | null;
  workingDays?: Weekday[];
  openingMinute?: number;
  closingMinute?: number;
}

/** Important operational alert generated by the backend (future: push notification). */
export interface OpsNotification {
  id: string;
  at: number;
  /** dedupe key, e.g. "F02:hot" */
  key: string;
  level: "critical" | "warning";
  title: string;
  body: string;
  fridgeId: string;
  missionId: string | null;
  /** delivery attempts per channel, e.g. { log: at, fcm: at } */
  delivered: Record<string, number>;
}

/** Registered device for future push notifications (FCM token). */
export interface Device {
  id: string;
  userId: string;
  platform: "android" | "web";
  token: string;
  createdAt: number;
  lastSeenAt: number;
}

export interface AppState {
  schema: 3;
  users: User[];
  sessions: Session[];
  missions: Mission[];
  missionSeq: number;
  players: Record<string, Player>;
  xpEvents: XpEvent[];
  rewardClaims: RewardClaim[];
  /** days already processed for the "day completed" bonus */
  dayBonusDays: number[];
  learning: LearningState;
  fridgeSettings: Record<string, FridgeSettings>;
  /** manual travel minutes between fridges: "F01>F02" → minutes */
  travelOverrides: Record<string, number>;
  settingsVersion: number;
  notifications: OpsNotification[];
  devices: Device[];
  lastAnalysisAt: number | null;
  lastSyncAt: number | null;
  sim: SimState | null;
}

const MAX_MISSIONS = 1500;

export function newPlayer(name: string, xp = 0): Player {
  return {
    name,
    xp,
    points: 0,
    streak: 0,
    bestStreak: 0,
    achievements: {},
    counters: { hotStockoutsPrevented: 0, wasteSaved: 0, perfectRoutesInRow: 0, fastUrgent: 0 },
  };
}

export function emptyState(): AppState {
  return {
    schema: 3,
    users: [],
    sessions: [],
    missions: [],
    missionSeq: 0,
    players: {},
    xpEvents: [],
    rewardClaims: [],
    dayBonusDays: [],
    learning: { forecastBias: {}, pairStats: {} },
    fridgeSettings: {},
    travelOverrides: {},
    settingsVersion: 0,
    notifications: [],
    devices: [],
    lastAnalysisAt: null,
    lastSyncAt: null,
    sim: null,
  };
}

/** Upgrades older state documents. v1 → missions reset (incompatible shape); v2 → adds auth & notifications. */
export function migrate(raw: Record<string, unknown> | null): AppState {
  const base = emptyState();
  if (!raw) return base;
  if (raw.schema === 3) return { ...base, ...(raw as unknown as AppState) };
  if (raw.schema === 2) return { ...base, ...(raw as unknown as Omit<AppState, "schema">), schema: 3, users: [], sessions: [], notifications: [], devices: [] };
  if (raw.schema === 1) {
    const oldPlayers = (raw.players ?? {}) as Record<string, { name: string; xp: number }>;
    return {
      ...base,
      learning: (raw.learning as LearningState) ?? base.learning,
      sim: (raw.sim as SimState) ?? null,
      players: Object.fromEntries(Object.entries(oldPlayers).map(([k, p]) => [k, newPlayer(p.name, p.xp)])),
    };
  }
  return base;
}

/** Keeps the document bounded. */
export function compact(state: AppState): AppState {
  state.missions = state.missions.slice(-MAX_MISSIONS);
  state.xpEvents = state.xpEvents.slice(-2000);
  state.notifications = state.notifications.slice(-300);
  const now = Date.now();
  state.sessions = state.sessions.filter((s) => s.expiresAt > now && (!s.revokedAt || now - s.revokedAt < 30 * 86_400_000));
  return state;
}

// ───────────────────────── drivers ─────────────────────────

export interface StateStore {
  readonly kind: "file" | "postgres";
  load(): Promise<AppState>;
  save(state: AppState): Promise<void>;
}

export class FileStore implements StateStore {
  readonly kind = "file" as const;
  private dir = path.join(process.cwd(), ".data");
  private file = path.join(this.dir, "app-state.json");

  async load(): Promise<AppState> {
    try {
      return migrate(JSON.parse(fs.readFileSync(this.file, "utf8")) as Record<string, unknown>);
    } catch {
      return emptyState();
    }
  }

  async save(state: AppState): Promise<void> {
    fs.mkdirSync(this.dir, { recursive: true });
    const tmp = `${this.file}.tmp`;
    fs.writeFileSync(tmp, JSON.stringify(compact(state)));
    fs.renameSync(tmp, this.file);
  }
}

export async function createStore(): Promise<StateStore> {
  const driver = process.env.STORE_DRIVER ?? (process.env.DATABASE_URL ? "postgres" : "file");
  if (driver === "postgres") {
    const { PgStore } = await import("./pgStore");
    return new PgStore(process.env.DATABASE_URL ?? "");
  }
  if (process.env.NODE_ENV === "production" && process.env.ALLOW_FILE_STORE !== "true") {
    throw new Error("Production requires STORE_DRIVER=postgres and DATABASE_URL (set ALLOW_FILE_STORE=true only for a single-machine demo).");
  }
  return new FileStore();
}
